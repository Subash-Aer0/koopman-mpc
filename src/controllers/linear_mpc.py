"""Error-state linear MPC on the hover linearization (baseline, replaces the LQR).

The MPC generates the full outer-loop command u = [ω (body FRD, rad/s), c (m/s²)]
for the low-level body-rate loop, at the model's sample time.

Coordinates (two levels; see the hover-trim derivation):
    1. Linearization about the hover trim in mean wind: δx = x − x*, δu = u − u*.
    2. Exact shift to the reference: e = δx − δx_ref(t), Δ = δu − δu_ref(t).
The reference (δx_ref, δu_ref) is generated by inverting the *linear* model
along p_ref(t), so it is a trajectory of the model and
    e_{k+1} = A e_k + B Δ_k
holds exactly for the model (LinearizedReference). Mean wind is in the trim;
turbulence δv_w is not predicted.

Problem solved every dt (docs/koopman_mpc_study_guide.md §3–5):
    min  Σ_{i=1}^{N-1} e_iᵀ Q e_i + e_Nᵀ P e_N + Σ_{i=0}^{N-1} Δ_iᵀ R Δ_i
    s.t. e_{i+1} = A e_i + B Δ_i,  e_0 measured
         u_lb ≤ u* + δu_ref,i + Δ_i ≤ u_ub                 (total command)
         |φ_i|, |θ_i| ≤ max_tilt,  i = 1..N                 (total attitude)
         terminal:  "polytope"   e_N ∈ O∞ of A + B K under tightened constraints
                    "equality"   e_N = 0
                    "cost_only"  none
P, K from the DARE on (A, B, Q, R). If a solve is infeasible, the step uses the
"cost_only" problem (input bounds only, always feasible) and is logged.

Units: e as x = [p (m), v (m/s), η (rad)], world NED, ZYX Euler.
"""
from dataclasses import dataclass, field
from typing import Callable

import numpy as np
from scipy.linalg import solve_discrete_are

from dynamics import dynamics as rigid_body
from dynamics._validation import as_finite_vector
from dynamics.quaternion import Quaternion

from .hover_model import (
    EULER, HoverModel, INPUT_DIM, PITCH, POS, RATE, ROLL, STATE_DIM, THRUST, VEL,
)
from .qp import condense, solve_qp
from .terminal_set import maximal_admissible_set

TERMINAL_MODES = ("polytope", "cost_only", "equality")
_MIN_EQUALITY_HORIZON = 3  # controllability index of the hover model (rate→angle→vel→pos)

# p_ref(t) -> (p, v, a, j), world NED, m, m/s, m/s², m/s³.
PositionDerivatives = Callable[[float], tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]]


@dataclass(frozen=True)
class LinearMPCSettings:
    """Weights, horizon, terminal mode and limits.

    Attributes:
        Q: (9, 9) symmetric PSD weight on e = [p, v, η] error.
        R: (4, 4) symmetric PD weight on Δ = [ω, c] − reference command.
        horizon: N ≥ 1 (≥ 3 for "equality").
        terminal: One of TERMINAL_MODES.
        u_lb, u_ub: (4,) bounds on the total command [ω_x, ω_y, ω_z, c].
        max_tilt: Bound on |roll| and |pitch| of the predicted vehicle, rad.
    """

    Q: np.ndarray
    R: np.ndarray
    horizon: int
    terminal: str
    u_lb: np.ndarray
    u_ub: np.ndarray
    max_tilt: float

    def __post_init__(self) -> None:
        Q = np.asarray(self.Q, dtype=float)
        R = np.asarray(self.R, dtype=float)
        if Q.shape != (STATE_DIM, STATE_DIM) or not np.allclose(Q, Q.T):
            raise ValueError(f"Q must be symmetric {STATE_DIM}x{STATE_DIM}")
        if np.min(np.linalg.eigvalsh(Q)) < -1e-12:
            raise ValueError("Q must be positive semidefinite")
        if R.shape != (INPUT_DIM, INPUT_DIM) or not np.allclose(R, R.T):
            raise ValueError(f"R must be symmetric {INPUT_DIM}x{INPUT_DIM}")
        if np.min(np.linalg.eigvalsh(R)) <= 0:
            raise ValueError("R must be positive definite")
        if self.terminal not in TERMINAL_MODES:
            raise ValueError(f"terminal must be one of {TERMINAL_MODES}, got {self.terminal!r}")
        minimum = _MIN_EQUALITY_HORIZON if self.terminal == "equality" else 1
        if not (isinstance(self.horizon, (int, np.integer)) and self.horizon >= minimum):
            raise ValueError(f"horizon must be an integer ≥ {minimum} for "
                             f"terminal={self.terminal!r}, got {self.horizon!r}")
        u_lb = as_finite_vector("u_lb", self.u_lb, INPUT_DIM)
        u_ub = as_finite_vector("u_ub", self.u_ub, INPUT_DIM)
        if np.any(u_lb >= u_ub):
            raise ValueError("u_lb must be below u_ub in every channel")
        if not (np.isfinite(self.max_tilt) and 0 < self.max_tilt < np.pi / 2):
            raise ValueError(f"max_tilt must be in (0, π/2) rad, got {self.max_tilt}")
        for name, value in (("Q", Q), ("R", R), ("u_lb", u_lb), ("u_ub", u_ub)):
            object.__setattr__(self, name, value)
        object.__setattr__(self, "horizon", int(self.horizon))


class LinearizedReference:
    """Model-consistent reference (δx_ref, δu_ref) for a position trajectory.

    Inverts the continuous linear model with yaw fixed at the trim yaw:
        δv̇ = A_vv δv + A_vφ δφ + A_vθ δθ + B_vc δc   ->  solve for (δφ, δθ, δc) given a_ref
        differentiate once                           ->  (δφ̇, δθ̇) from j_ref
        δη̇ = W(η*) δω                                ->  δω
    The trim is at p = 0, so δp_ref = p_ref.
    """

    def __init__(self, model: HoverModel, derivatives: PositionDerivatives):
        self.model = model
        self.derivatives = derivatives
        A_c, B_c = model.A_c, model.B_c
        self._A_vv = A_c[VEL, VEL]
        self._M = np.column_stack([A_c[VEL, ROLL], A_c[VEL, PITCH], B_c[VEL, THRUST]])
        self._W = B_c[EULER, RATE]
        if np.linalg.cond(self._M) > 1e6 or np.linalg.cond(self._W) > 1e6:
            raise ValueError("hover model is not invertible for (roll, pitch, thrust)")

    def __call__(self, t: float) -> tuple[np.ndarray, np.ndarray]:
        """δx_ref (9,) and δu_ref (4,) at time t, s."""
        p, v, a, j = (np.asarray(value, dtype=float) for value in self.derivatives(t))
        roll, pitch, d_thrust = np.linalg.solve(self._M, a - self._A_vv @ v)
        roll_dot, pitch_dot, _ = np.linalg.solve(self._M, j - self._A_vv @ a)
        omega = np.linalg.solve(self._W, np.array([roll_dot, pitch_dot, 0.0]))
        dx = np.concatenate([p - self.model.x_trim[POS], v, [roll, pitch, 0.0]])
        du = np.concatenate([omega, [d_thrust]])
        return dx, du


@dataclass
class MPCLog:
    """One row per solve: time, fallback flag, solver status and timing, error, command."""

    t: list = field(default_factory=list)
    fallback: list = field(default_factory=list)
    exitflag: list = field(default_factory=list)
    solve_time: list = field(default_factory=list)
    error: list = field(default_factory=list)
    command: list = field(default_factory=list)

    def arrays(self) -> dict[str, np.ndarray]:
        return {name: np.asarray(getattr(self, name)) for name in
                ("t", "fallback", "exitflag", "solve_time", "error", "command")}

    def save(self, path) -> None:
        np.savez(path, **self.arrays())


def wrap_angle(angle):
    """Wrap to [−π, π)."""
    return (np.asarray(angle) + np.pi) % (2 * np.pi) - np.pi


def outer_state(x) -> np.ndarray:
    """13-state rigid-body x (dynamics.py) -> 9-state [p, v, η] of the hover model."""
    x = as_finite_vector("x", x, rigid_body.STATE_DIM)
    euler = Quaternion(x[rigid_body.QUAT]).normalize().to_euler()
    return np.concatenate([x[rigid_body.POS], x[rigid_body.VEL], euler])


class LinearMPC:
    """Error-state linear MPC; call with (t, 13-state x) every `period` seconds."""

    def __init__(self, model: HoverModel, settings: LinearMPCSettings,
                 reference: LinearizedReference, reference_duration: float):
        """
        Args:
            model: Discrete hover model; its dt is the MPC period.
            settings: Weights, horizon, terminal mode, limits.
            reference: Model-consistent reference generator.
            reference_duration: Time span, s, over which the reference is used.
                The reference is sampled over [0, reference_duration + N dt]
                to tighten the terminal-set constraints by the reference's
                own use of inputs and tilt, so one constant O∞ is valid at
                every time.

        Raises:
            ValueError: If the reference needs more input or tilt than allowed.
        """
        self.model = model
        self.settings = settings
        self.reference = reference
        self.period = model.dt
        N = settings.horizon
        A, B = model.A, model.B
        self.P = solve_discrete_are(A, B, settings.Q, settings.R)
        self.K = -np.linalg.solve(settings.R + B.T @ self.P @ B, B.T @ self.P @ A)

        self._tilt_rows = np.zeros((2, STATE_DIM))
        self._tilt_rows[0, ROLL] = 1.0
        self._tilt_rows[1, PITCH] = 1.0
        self._cond = condense(A, B, np.zeros((STATE_DIM, 1)), np.eye(STATE_DIM),
                              settings.Q, settings.R, N, P=self.P, E=self._tilt_rows)
        self._Phi_N = self._cond.Phi[-STATE_DIM:]
        self._Gamma_N = self._cond.Gamma[-STATE_DIM:]
        self._u_trim = model.u_trim
        self._tilt_trim = model.x_trim[[ROLL, PITCH]]

        # Reference use of inputs and tilt over the run, for the constant terminal set.
        times = np.arange(0.0, reference_duration + (N + 1) * model.dt, model.dt)
        refs = [reference(t) for t in times]
        du_ref = np.array([du for _, du in refs])
        tilt_ref = np.array([dx[[ROLL, PITCH]] for dx, _ in refs]) + self._tilt_trim
        self._delta_lb = settings.u_lb - self._u_trim - du_ref.min(axis=0)
        self._delta_ub = settings.u_ub - self._u_trim - du_ref.max(axis=0)
        tilt_lb = -settings.max_tilt - tilt_ref.min(axis=0)
        tilt_ub = settings.max_tilt - tilt_ref.max(axis=0)
        if np.any(self._delta_lb >= 0) or np.any(self._delta_ub <= 0) \
                or np.any(tilt_lb >= 0) or np.any(tilt_ub <= 0):
            raise ValueError("the reference uses more input or tilt than the limits allow; "
                             "no margin is left for feedback")
        self.terminal_set = None
        if settings.terminal == "polytope":
            H = np.vstack([self._tilt_rows, -self._tilt_rows, self.K, -self.K])
            h = np.concatenate([tilt_ub, -tilt_lb, self._delta_ub, -self._delta_lb])
            self.terminal_set = maximal_admissible_set(A + B @ self.K, H, h)
        self.log = MPCLog()
        self._previous = None

    @property
    def fallback_count(self) -> int:
        return int(np.sum(self.log.fallback))

    def error_state(self, t: float, x) -> np.ndarray:
        """e = (x₉ − x*) − δx_ref(t), angles wrapped; x is the 13-state."""
        dx_ref, _ = self.reference(t)
        e = outer_state(x) - self.model.x_trim - dx_ref
        e[EULER] = wrap_angle(e[EULER])
        return e

    def __call__(self, t: float, x) -> np.ndarray:
        """Total command u = [ω, c] for the 13-state x at time t."""
        s, N, dt = self.settings, self.settings.horizon, self.model.dt
        e0 = self.error_state(t, x)
        refs = [self.reference(t + i * dt) for i in range(N + 1)]
        du_ref = np.array([du for _, du in refs[:N]])
        tilt_ref = np.array([dx[[ROLL, PITCH]] for dx, _ in refs[1:]]) + self._tilt_trim

        no_wind = np.zeros(1)
        f = self._cond.linear_term(e0, no_wind)
        lb = (s.u_lb - self._u_trim - du_ref).ravel()
        ub = (s.u_ub - self._u_trim - du_ref).ravel()
        g_lb, g_ub = self._cond.state_bounds(e0, no_wind, -s.max_tilt - tilt_ref,
                                             s.max_tilt - tilt_ref)
        G, rows_lb, rows_ub = [self._cond.G], [g_lb], [g_ub]
        if s.terminal == "polytope":
            H_f, h_f = self.terminal_set
            G.append(H_f @ self._Gamma_N)
            rows_lb.append(np.full(len(h_f), -np.inf))
            rows_ub.append(h_f - H_f @ self._Phi_N @ e0)
        elif s.terminal == "equality":
            G.append(self._Gamma_N)
            rows_lb.append(-self._Phi_N @ e0)
            rows_ub.append(-self._Phi_N @ e0)

        warm = None
        if self._previous is not None:  # shifted previous plan, last move repeated
            warm = np.concatenate([self._previous[INPUT_DIM:], self._previous[-INPUT_DIM:]])
        result = solve_qp(self._cond.H, f, lb, ub, np.vstack(G), np.concatenate(rows_lb),
                          np.concatenate(rows_ub), x0=warm)
        fallback = not result.solved
        if fallback:
            result = solve_qp(self._cond.H, f, lb, ub)
            if not result.solved:
                raise RuntimeError(f"input-bound-only MPC failed at t = {t} s "
                                   f"(exitflag {result.exitflag})")
        self._previous = result.x
        u = self._u_trim + du_ref[0] + result.x[:INPUT_DIM]
        # The QP enforces the bounds up to solver tolerance; clip only that round-off.
        u = np.clip(u, s.u_lb, s.u_ub)

        self.log.t.append(t)
        self.log.fallback.append(fallback)
        self.log.exitflag.append(result.exitflag)
        self.log.solve_time.append(result.solve_time)
        self.log.error.append(e0)
        self.log.command.append(u)
        return u
